const dictionaries = { en, el } as const;

export type TranslationKey = keyof typeof en;

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey) => string;
  /** Translates a caught error (from a Tauri command rejection or anything else) into a display
   * string in the current locale — combines `toAppError` with `translateErrorMessage`. Use this
   * for ad hoc "row error" display; `useFormError` already does the equivalent for forms. */
  te: (err: unknown) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function readStoredLocale(): Locale {
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
    if (stored === "el" || stored === "en") return stored;
  } catch {
    // localStorage unavailable (e.g. private/blocked storage) — fall through to the default.
  }
  return DEFAULT_LOCALE;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readStoredLocale);

  useEffect(() => {
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    } catch {
      // Best-effort persistence only — the app still works within this session if it fails.
    }
  }, [locale]);

  const value: I18nContextValue = {
    locale,
    setLocale: setLocaleState,
    t: (key) => dictionaries[locale][key],
    te: (err) => translateErrorMessage(toAppError(err).message, locale),
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return ctx;
}
