/**
 * Minimal i18n scaffold (Phase 5 decision, revisited when Greek shipped) — a plain key -> string
 * lookup, not a full i18n library (react-i18next, etc.). The app doesn't need plural rules,
 * interpolation, or lazy-loaded translation bundles, so pulling in that machinery would be
 * overengineering for two flat locales.
 *
 * `en` is the source of truth for the key set; `el`'s type is derived from it (`Record<keyof
 * typeof en, string>`), so TypeScript fails the build if a key is missing from either locale —
 * important at ~500 keys, where a silent gap would just render `undefined` at runtime.
 *
 * Backend validation error messages (Rust `AppError`) are a separate concern, translated via
 * `src/lib/errorTranslations.ts` — see that file for why they can't just be dictionary keys.
 */

